# Test-only settings. Guarded on argv being literally `manage.py test ...`, so
# gunicorn, migrate, shell and every other command are untouched — nothing here
# can reach the deploy.
#
# Two things, both measured on 4 Aug 2026 against a 17-minute suite:
#
# 1. PBKDF2 is deliberately slow (~600k iterations, ~510 ms a hash). That is
#    correct in production and ruinous in tests: `tests_timeouts._member_client`
#    creates two users and logs in, which is ~1.54 s of hashing, and it sits in
#    setUp, so it runs once per test rather than once per class. 621 of 828
#    tests pay it — about 16 of the 17 minutes. The actual test logic is ~4
#    seconds. MD5 here is not a security decision; no password set under test
#    outlives the run.
#
# 2. SQLite's test database defaults to in-memory, which `--keepdb` cannot keep,
#    so all three databases were rebuilt through 44 migrations on every
#    invocation — a fixed ~15 s, paid even to run one test. Pointing TEST NAME
#    at a file makes --keepdb work: a warm single-module run goes 104 s -> 3 s.
#
# Measured together: the full Django suite runs 864 tests in ~20 s.
if sys.argv[1:2] == ['test']:
    PASSWORD_HASHERS = ['django.contrib.auth.hashers.MD5PasswordHasher']
    # The migration's second alias always exists under test, so `academy_db_copy`
    # can be driven for real between two databases that both carry the academy
    # schema. Preserving every primary key is the property the whole move rests
    # on — a renumbered user is a session pointing at the wrong person — and it
    # is not a property you can check without somewhere to copy to.
    DATABASES.setdefault('academy_sqlite', {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': BASE_DIR / 'db_academy_source.sqlite3',
    })
    # `default` is `{}` and must stay that way — Django decides a database is
    # unconfigured by looking for ENGINE, and a `default` carrying a TEST block
    # is an alias the test runner would try to create.
    #
    # DEPENDENCIES is the half that is not obvious. Django defaults every
    # non-default alias to `TEST['DEPENDENCIES'] = ['default']`, so that the
    # default database is set up first. With `default` empty there is nothing
    # to set up and nothing to depend on, and the runner fails resolving the
    # order — `ImproperlyConfigured: Circular dependency in TEST[DEPENDENCIES]`,
    # which names neither the alias nor `default` and reads like a settings
    # typo. Stating the empty list is the documented answer for a project with
    # no default database.
    for _alias, _config in DATABASES.items():
        if not _config:
            continue
        _config.setdefault('TEST', {})
        _config['TEST']['NAME'] = str(BASE_DIR / f'test_{_alias}.sqlite3')
        _config['TEST']['DEPENDENCIES'] = []


