# --- Cache ------------------------------------------------------------------
# There was no CACHES setting at all, so Django's own default applied:
# local-memory, per process. Five things share it — the gene search index, the
# public antibody search index, the extension snapshot, the bulk archive's
# "does it exist yet" check, and the API rate limiter — and each gunicorn worker
# keeps its own copy. For the first four that is only waste: they are pure
# speed, so a cold worker is a slow answer and never a wrong one. For the rate
# limiter it is the ceiling, because there the tally *is* the limit — a consumer
# gets roughly the nominal rate per worker, which is what `core.W003` reports.
#
# Set `CACHE_URL` (or Render's `REDIS_URL`) to a Redis-compatible instance — a
# Render Key Value service — and the same code becomes exact. Nothing else has
# to change; `api_throttle.using_shared_cache()` reads the backend name and
# `core.W003` goes quiet on its own.
#
# **`IGNORE_EXCEPTIONS` is the whole reason for django-redis** rather than
# Django's built-in `RedisCache`, which raises when the instance is unreachable.
# Everything in this project degrades rather than fails — a dead UniProt returns
# `unchecked`, a missing stylesheet falls back to the CDN — and a cache is the
# wrong thing to take a site down for: the gene pages and the search box would
# 500 over an unavailable *optimisation*. The trade is stated rather than
# hidden: with the cache unreachable, `_hit` cannot accumulate, so the API
# throttle fails **open**. That is the right direction for a guard on data that
# is public anyway, and it is why the real ceiling belongs at Cloudflare, which
# sees the connection and cannot be talked out of it.
_cache_url = os.environ.get('CACHE_URL') or os.environ.get('REDIS_URL', '')

if _cache_url:
    CACHES = {
        'default': {
            'BACKEND': 'django_redis.cache.RedisCache',
            'LOCATION': _cache_url,
            'OPTIONS': {
                'CLIENT_CLASS': 'django_redis.client.DefaultClient',
                'IGNORE_EXCEPTIONS': True,
            },
            'KEY_PREFIX': 'oga',
        }
    }
else:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.locmem.LocMemCache',
            'LOCATION': 'oga',
        }
    }


